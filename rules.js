const days = (m) => {
  const hit = m[0].match(/(\d{1,3})\s?(일|개월|달|days?|months?)/i);
  if (!hit) return null;
  const n = parseInt(hit[1], 10);
  const unit = hit[2].toLowerCase();
  const isMonth = unit === '개월' || unit === '달' || unit.startsWith('month');
  return { n, days: isMonth ? n * 30 : n, months: isMonth ? n : n / 30 };
};

